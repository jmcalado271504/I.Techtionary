class TypeScriptPage extends StatefulWidget {
  final String? initialTopic;

  const TypeScriptPage({
    super.key,
    this.initialTopic,
  });

  @override
  State<TypeScriptPage> createState() => _TypeScriptPageState();
}

class _TypeScriptPageState extends State<TypeScriptPage> {
  String currentTopic = "TS Introduction";
  bool showMenu = false;
  static const String techName = "TypeScript";

  bool get isHistoryLesson {
    return typescriptHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...typescriptModules,
      ...typescriptHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }
    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "TypeScript Lessons";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && typescriptModules.isNotEmpty) {
          currentTopic = typescriptModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && typescriptModules.length > 1) {
          currentTopic = typescriptModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && typescriptModules.length > 2) {
          currentTopic = typescriptModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && typescriptModules.length > 3) {
          currentTopic = typescriptModules[3].lessons.first;
        } else if (currentTopic.contains("Module 5") && typescriptModules.length > 4) {
          currentTopic = typescriptModules[4].lessons.first;
        } else if (currentTopic.contains("Module 6") && typescriptModules.length > 5) {
          currentTopic = typescriptModules[5].lessons.first;
        } else if (currentTopic.contains("Module 7") && typescriptModules.length > 6) {
          currentTopic = typescriptModules[6].lessons.first;
        } else {
          currentTopic = "TS Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
      case "Release Date":
        return "October 1, 2012\n\nTypeScript was officially released by Microsoft on October 1, 2012 as an open-source programming language.";
      case "Creator":
        return "Anders Hejlsberg\n\nTypeScript was created by Anders Hejlsberg, the creator of C#, while working at Microsoft.";
      case "Country of Origin":
        return "United States\n\nTypeScript was developed by Microsoft in Redmond, Washington, USA.";
      case "Why It Was Created":
        return "TypeScript was created to improve JavaScript development by adding static typing, better tooling, and improved code maintainability for large-scale applications while remaining compatible with JavaScript.";
      case "Brief History":
        return "As JavaScript applications became larger and more complex, Microsoft developed TypeScript to provide optional static typing and modern language features. Introduced in 2012, TypeScript quickly gained popularity because it compiles to standard JavaScript and integrates seamlessly with existing JavaScript projects. Today, it is widely used in enterprise applications and modern frameworks such as Angular, React, and Vue.";
      case "Evolution Timeline":
        return "2012\nTypeScript Released\n│\n\n2014\nGrowing Community Adoption\n│\n\n2016\nTypeScript 2.0\nMajor Type System Improvements\n│\n\n2020\nTypeScript 4.x Series\n│\n\n2023\nTypeScript 5.x Released\n│\n\nToday\nContinuously Updated by Microsoft";
      case "Major Milestones":
        return "• 2012 – TypeScript was officially released.\n\n• Created by Anders Hejlsberg at Microsoft.\n\n• Became the primary language for Angular development.\n\n• Widely adopted by React, Vue, Node.js, and enterprise applications.\n\n• Today – One of the most popular programming languages for modern web development.";
      case "Famous Quote":
        return "\"JavaScript that scales.\"\n\n— TypeScript Official Website";
      default:
        return "Learn how TypeScript was created and evolved over time.";
    }
  }

