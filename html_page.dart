class HtmlPage extends StatefulWidget {
  final String? initialTopic;

  const HtmlPage({super.key, this.initialTopic});

  @override
  State<HtmlPage> createState() => _HtmlPageState();
}

class _HtmlPageState extends State<HtmlPage> {
  String currentTopic = "HTML Introduction";
  bool showMenu = false;

  bool get isHistoryLesson {
    return HtmlHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...htmlModules,
      ...HtmlHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "HTML Lessons";
      const String techName = "HTML";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && htmlModules.isNotEmpty) {
          currentTopic = htmlModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && htmlModules.length > 1) {
          currentTopic = htmlModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && htmlModules.length > 2) {
          currentTopic = htmlModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && htmlModules.length > 3) {
          currentTopic = htmlModules[3].lessons.first;
        } else if (currentTopic.contains("Module 5") && htmlModules.length > 4) {
          currentTopic = htmlModules[4].lessons.first;
        } else if (currentTopic.contains("Module 6") && htmlModules.length > 5) {
          currentTopic = htmlModules[5].lessons.first;
        } else if (currentTopic.contains("Module 7") && htmlModules.length > 6) {
          currentTopic = htmlModules[6].lessons.first;
        } else {
          currentTopic = "HTML Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
      case "Release Date":
        return "1991 - HTML (HyperText Markup Language) was first publicly introduced in 1991 by Tim Berners-Lee. It became the standard language for creating web pages and is still the foundation of every website today.";
      case "Creator":
        return "Tim Berners-Lee - A British computer scientist who invented the World Wide Web while working at CERN. He developed HTML together with HTTP and URLs to make sharing information over the internet possible.";
      case "Country of Origin":
        return "Switzerland - HTML was created at CERN (European Organization for Nuclear Research) located in Geneva, Switzerland, where Tim Berners-Lee developed the first web technologies.";
      case "Why It Was Created":
        return "HTML was created to allow researchers and scientists to easily share documents and information over the internet. It provided a simple way to connect documents using hyperlinks.";
      case "Brief History":
        return "HTML began in 1991 as a simple markup language containing only a small number of tags. As the web rapidly expanded, HTML evolved to support images, tables, forms, multimedia, and modern web applications (HTML5).";
      case "Evolution Timeline":
        return "1991: First HTML Version | 1995: HTML 2.0 | 1997: HTML 3.2 | 1999: HTML 4.01 | 2014: HTML5 Became Official | Today: Living HTML Standard";
      case "Major Milestones":
        return "1991: Introduced by Tim Berners-Lee | 1995: HTML 2.0 First Official Standard | 1997: HTML 3.2 Added Tables & Applets | 1999: HTML 4.01 Improved Scripting | 2014: HTML5 W3C Recommendation | Today: Living Standard by WHATWG";
      case "Famous Quote":
        return "\"The power of the Web is in its universality. Access by everyone regardless of disability is an essential aspect.\" — Tim Berners-Lee";
      default:
        return "Learn how HTML was created and evolved over time.";
    }
  }

