class AngularPage extends StatefulWidget {
  final String? initialTopic;

  const AngularPage({super.key, this.initialTopic});

  @override
  State<AngularPage> createState() => _AngularPageState();
}

class _AngularPageState extends State<AngularPage> {
  String currentTopic = "Angular Introduction";
  bool showMenu = false;

  bool get isHistoryLesson {
    return angularHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...angularModules,
      ...angularHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "Angular Lessons";
      const String techName = "Angular";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && angularModules.isNotEmpty) {
          currentTopic = angularModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && angularModules.length > 1) {
          currentTopic = angularModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && angularModules.length > 2) {
          currentTopic = angularModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && angularModules.length > 3) {
          currentTopic = angularModules[3].lessons.first;
        } else if (currentTopic.contains("Module 5") && angularModules.length > 4) {
          currentTopic = angularModules[4].lessons.first;
        } else if (currentTopic.contains("Module 6") && angularModules.length > 5) {
          currentTopic = angularModules[5].lessons.first;
        } else {
          currentTopic = "Angular Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
      case "Release Date":
        return "September 14, 2016 - Angular (commonly called Angular 2+) was officially released on September 14, 2016. It was a complete rewrite of AngularJS and introduced a modern framework for building web applications.";
      case "Creator":
        return "Google - Angular is developed and maintained by Google with contributions from a large open-source community. The original AngularJS project was created by Miško Hevery and Adam Abrons.";
      case "Country of Origin":
        return "United States - Angular was developed by Google in the United States and has become one of the most popular frameworks for front-end web development.";
      case "Why It Was Created":
        return "Angular was created to simplify the development of large, dynamic web applications by providing powerful tools such as components, dependency injection, routing, and two-way data binding.";
      case "Brief History":
        return "The first version, AngularJS, was released in 2010. As web development evolved, Google completely redesigned the framework and released Angular in 2016 based on TypeScript.";
      case "Evolution Timeline":
        return "2010: AngularJS Released | 2016: Angular 2 Released (Complete Rewrite) | 2017: Angular 4 | 2019: Angular 8 (Differential Loading) | 2021: Angular 13 (Ivy Rendering) | Today: Angular 18+";
      case "Major Milestones":
        return "2010: AngularJS introduced | 2016: Angular 2 completely redesigned framework | 2017: Regular release schedule adopted | 2019: Differential loading added | 2021: Ivy fully adopted | Today: Continuous performance evolution";
      case "Famous Quote":
        return "\"One framework. Mobile and desktop.\" — Angular Team";
      default:
        return "Learn how Angular was created and evolved over time.";
    }
  }

