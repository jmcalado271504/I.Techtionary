class JQueryPage extends StatefulWidget {
  final String? initialTopic;

  const JQueryPage({super.key, this.initialTopic});

  @override
  State<JQueryPage> createState() => _JQueryPageState();
}

class _JQueryPageState extends State<JQueryPage> {
  String currentTopic = "jQuery Introduction";
  bool showMenu = false;
  static const String techName = "jQuery";

  bool get isHistoryLesson {
    return jqueryHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...jqueryModules,
      ...jqueryHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "jQuery Lessons";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && jqueryModules.isNotEmpty) {
          currentTopic = jqueryModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && jqueryModules.length > 1) {
          currentTopic = jqueryModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && jqueryModules.length > 2) {
          currentTopic = jqueryModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && jqueryModules.length > 3) {
          currentTopic = jqueryModules[3].lessons.first;
        } else if (currentTopic.contains("Module 5") && jqueryModules.length > 4) {
          currentTopic = jqueryModules[4].lessons.first;
        } else {
          currentTopic = "jQuery Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

