        return "• 2006 – jQuery 1.0 was officially released.\n\n• 2007 – Became one of the fastest-growing JavaScript libraries.\n\n• 2011 – jQuery Mobile enabled mobile web development.\n\n• 2016 – jQuery 3.0 introduced improved performance and modern JavaScript support.\n\n• Today – jQuery continues to support millions of websites worldwide.";
      case "Famous Quote":
        return "\"Write Less, Do More.\"\n\n— John Resig";
      default:
        return "Learn how jQuery was created and evolved over time.";
    }
  }

