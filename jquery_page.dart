        return "John Resig\n\nJohn Resig created jQuery while working to simplify JavaScript programming and eliminate browser compatibility issues that developers commonly faced.";
      case "Country of Origin":
        return "United States\n\njQuery was developed in the United States and became one of the most influential JavaScript libraries in web development.";
      case "Why It Was Created":
        return "jQuery was created to simplify JavaScript programming by providing an easy-to-use syntax for DOM manipulation, event handling, animations, and AJAX while ensuring compatibility across multiple web browsers.";
      case "Brief History":
        return "Before jQuery, developers had to write lengthy JavaScript code that often behaved differently in each browser. John Resig introduced jQuery in 2006 with the philosophy 'Write Less, Do More.' It quickly became the world's most popular JavaScript library and powered millions of websites. Although modern JavaScript has replaced many of its features, jQuery is still widely used in legacy systems and existing web applications.";
      case "Evolution Timeline":
        return "2006\njQuery 1.0 Released\n│\n\n2007\nRapid Community Growth\n│\n\n2011\njQuery Mobile Released\n│\n\n2013\njQuery 2.0\nDropped Old Browser Support\n│\n\n2016\njQuery 3.0 Released\n│\n\nToday\njQuery 3.x";
