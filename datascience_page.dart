class DataSciencePage extends StatefulWidget {
  final String? initialTopic;

  const DataSciencePage({
    super.key,
    this.initialTopic,
  });

  @override
  State<DataSciencePage> createState() => _DataSciencePageState();
}

class _DataSciencePageState extends State<DataSciencePage> {
  String currentTopic = "Data Science Introduction";
  bool showMenu = false;
  static const String techName = "DataScience";

  bool get isHistoryLesson {
    return datascienceHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...dsModules,
      ...datascienceHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "Data Science Lessons";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && dsModules.isNotEmpty) {
          currentTopic = dsModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && dsModules.length > 1) {
          currentTopic = dsModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && dsModules.length > 2) {
          currentTopic = dsModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && dsModules.length > 3) {
          currentTopic = dsModules[3].lessons.first;
        } else if (currentTopic.contains("Module 5") && dsModules.length > 4) {
          currentTopic = dsModules[4].lessons.first;
        } else if (currentTopic.contains("Module 6") && dsModules.length > 5) {
          currentTopic = dsModules[5].lessons.first;
        } else if (currentTopic.contains("Module 7") && dsModules.length > 6) {
          currentTopic = dsModules[6].lessons.first;
        } else if (currentTopic.contains("Module 8") && dsModules.length > 7) {
          currentTopic = dsModules[7].lessons.first;
        } else {
          currentTopic = "Data Science Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
      case "Release Date":
        return "2001\n\nThe term 'Data Science' became widely recognized in 2001 when statistician William S. Cleveland proposed it as an independent discipline combining statistics, computing, and data analysis.";
      case "Creator":
        return "William S. Cleveland\n\nAlthough many researchers contributed to the field, William S. Cleveland is widely credited for formally defining Data Science as a distinct discipline in 2001.";
      case "Country of Origin":
        return "United States\n\nThe modern concept of Data Science was formalized in the United States through academic research and industry innovation.";
      case "Why It Was Created":
        return "Data Science was created to help organizations collect, analyze, and interpret massive amounts of data. By combining statistics, programming, and machine learning, it enables data-driven decision-making and predictive analysis.";
      case "Brief History":
        return "The roots of Data Science began with statistics and data analysis. As computing technology advanced and data volumes increased, the field evolved to include artificial intelligence, machine learning, and big data technologies. Today, Data Science plays a vital role in business, healthcare, finance, education, and scientific research.";
      case "Evolution Timeline":
        return "1960s\nEarly Data Analysis\n│\n\n1970s\nDatabase Systems\n│\n\n2001\nData Science Defined\n│\n\n2010\nBig Data Revolution\n│\n\n2012\nMachine Learning Boom\n│\n\nToday\nAI & Generative AI Era";
      case "Major Milestones":
        return "• 2001 – William S. Cleveland formally defined Data Science.\n\n• 2010 – Big Data technologies became widely adopted.\n\n• 2012 – Machine Learning gained mainstream popularity.\n\n• 2020 – Artificial Intelligence accelerated Data Science applications.\n\n• Today – Data Science powers AI, analytics, automation, and decision-making across industries.";
      case "Famous Quote":
        return "\"Data is the new oil.\"\n\n— Clive Humby";
      default:
        return "Learn how Data Science was created and evolved over time.";
    }
  }

