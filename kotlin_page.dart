        return "JetBrains\n\nKotlin was developed by JetBrains, the company behind IntelliJ IDEA. The project was led by Andrey Breslav and a team of software engineers.";
      case "Country of Origin":
        return "Czech Republic\n\nKotlin was created by JetBrains, a software company founded in Prague, Czech Republic.";
      case "Why It Was Created":
        return "Kotlin was created to improve Java by making programming more concise, safer, and more productive while remaining fully compatible with existing Java code and libraries.";
      case "Brief History":
        return "JetBrains began developing Kotlin in 2010 to address limitations they experienced while using Java. The language was announced publicly in 2011, and Kotlin 1.0 was released in 2016. In 2017, Google announced Kotlin as an official language for Android development, greatly increasing its popularity. Today, Kotlin is widely used for Android, backend, desktop, and multiplatform applications.";
      case "Evolution Timeline":
        return "2010\nDevelopment Begins\n│\n\n2011\nProject Announced\n│\n\n2016\nKotlin 1.0 Released\n│\n\n2017\nOfficial Android Language\n│\n\n2021\nKotlin Multiplatform Expanded\n│\n\nToday\nKotlin 2.x";
