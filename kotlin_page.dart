class KotlinPage extends StatefulWidget {
  final String? initialTopic;

  const KotlinPage({
    super.key,
    this.initialTopic,
  });

  @override
  State<KotlinPage> createState() => _KotlinPageState();
}

class _KotlinPageState extends State<KotlinPage> {
  String currentTopic = "Kotlin Introduction";
  bool showMenu = false;
  static const String techName = "Kotlin";

  bool get isHistoryLesson {
    return kotlinHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...kotlinModules,
      ...kotlinHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "Kotlin Lessons";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && kotlinModules.isNotEmpty) {
          currentTopic = kotlinModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && kotlinModules.length > 1) {
          currentTopic = kotlinModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && kotlinModules.length > 2) {
          currentTopic = kotlinModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && kotlinModules.length > 3) {
          currentTopic = kotlinModules[3].lessons.first;
        } else {
          currentTopic = "Kotlin Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
