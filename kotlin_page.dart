        return "• 2011 – Kotlin project was publicly announced.\n\n• 2016 – Kotlin 1.0 officially released.\n\n• 2017 – Google declared Kotlin an official Android language.\n\n• 2019 – Kotlin became Google's preferred language for Android development.\n\n• Today – Kotlin powers Android, backend, desktop, and multiplatform applications.";
      case "Famous Quote":
        return "\"Kotlin is a better language for better software.\"\n\n— JetBrains";
      default:
        return "Learn how Kotlin was created and evolved over time.";
    }
  }

