        return "1971\nCreeper Worm Created\n│\n\n1972\nReaper Program Developed\n│\n\n1988\nMorris Worm Attack\n│\n\n1990s\nCommercial Antivirus Software\n│\n\n2000s\nRise of Cybercrime\n│\n\nToday\nAI-Driven Cybersecurity";
