      case "Country of Origin":
        return "United States\n\nThe foundations of cybersecurity began in the United States alongside the development of ARPANET, the precursor to the modern Internet.";
      case "Why It Was Created":
        return "Cybersecurity was developed to protect computers, networks, software, and digital information from unauthorized access, cyberattacks, malware, data breaches, and other digital threats.";
