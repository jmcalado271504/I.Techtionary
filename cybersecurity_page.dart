class CyberSecurityPage extends StatefulWidget {
  final String? initialTopic;

  const CyberSecurityPage({
    super.key,
    this.initialTopic,
  });

  @override
  State<CyberSecurityPage> createState() => _CyberSecurityPageState();
}

class _CyberSecurityPageState extends State<CyberSecurityPage> {
  String currentTopic = "CyberSecurity Introduction";
  bool showMenu = false;
  static const String techName = "CyberSecurity";

  bool get isHistoryLesson {
    return cybersecurityHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...cyberSecurityModules,
      ...cybersecurityHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "CyberSecurity Lessons";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && cyberSecurityModules.isNotEmpty) {
          currentTopic = cyberSecurityModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && cyberSecurityModules.length > 1) {
          currentTopic = cyberSecurityModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && cyberSecurityModules.length > 2) {
          currentTopic = cyberSecurityModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && cyberSecurityModules.length > 3) {
          currentTopic = cyberSecurityModules[3].lessons.first;
        } else {
          currentTopic = "CyberSecurity Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
