        return "• 1971 – Creeper became the first self-replicating computer program.\n\n• 1972 – Reaper became the first antivirus-like program.\n\n• 1988 – Morris Worm highlighted Internet security risks.\n\n• Development of firewalls, encryption, IDS, and antivirus software.\n\n• Today – Cybersecurity protects cloud computing, AI systems, IoT devices, and global digital infrastructure.";
