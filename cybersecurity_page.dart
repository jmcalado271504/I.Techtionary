        return "As computer systems became connected through networks, protecting information became increasingly important. The first computer worm, Creeper, appeared in the early 1970s, followed by Reaper, considered the first antivirus program. Since then, cybersecurity has expanded into a major discipline covering network security, ethical hacking, digital forensics, cloud security, and artificial intelligence-driven defense systems. Today, cybersecurity protects governments, businesses, and individuals worldwide.";
