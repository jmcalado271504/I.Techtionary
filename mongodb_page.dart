        return "2007\n10gen Founded\n│\n\n2009\nMongoDB First Release\n│\n\n2013\nMongoDB 2.4\nPerformance Improvements\n│\n\n2017\nMongoDB Atlas Launched\n│\n\n2018\nMongoDB 4.0\nMulti-Document Transactions\n│\n\nToday\nMongoDB 8.x";
