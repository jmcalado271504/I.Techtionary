      case "Country of Origin":
        return "United States\n\nMongoDB was created in New York, United States, by 10gen Inc., which later became MongoDB Inc.";
      case "Why It Was Created":
        return "MongoDB was created to provide a flexible, scalable, and high-performance database capable of handling large amounts of unstructured data using documents instead of tables.";
