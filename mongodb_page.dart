class MongoDbPage extends StatefulWidget {
  final String? initialTopic;

  const MongoDbPage({super.key, this.initialTopic});

  @override
  State<MongoDbPage> createState() => _MongoDbPageState();
}

class _MongoDbPageState extends State<MongoDbPage> {
  String currentTopic = "MongoDB Get Started";
  bool showMenu = false;
  static const String techName = "MongoDb";

  bool get isHistoryLesson {
    return mongodbHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...mongodbModules,
      ...mongodbHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }
    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "MongoDB Lessons";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && mongodbModules.isNotEmpty) {
          currentTopic = mongodbModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && mongodbModules.length > 1) {
          currentTopic = mongodbModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && mongodbModules.length > 2) {
          currentTopic = mongodbModules[2].lessons.first;
        } else {
          currentTopic = "MongoDB Get Started";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

