  Map<String, dynamic> getTopicData(String topic) {
    try {
      final lesson = rLessons.firstWhere(
            (lesson) => lesson.title == topic,
      );

      return {
        "description": lesson.description,
        "code": lesson.code,
        "previewCode": lesson.previewCode ?? lesson.code,
        "extra": lesson.notes,
      };
    } catch (e) {
      return {
        "description": "Lesson not found.",
        "code": "",
        "previewCode": "",
        "extra": "",
      };
    }
  }

  // ===========================================================================
  // TOPIC CONTENT ROUTING
  // ===========================================================================
  Widget getTopicContent(BuildContext context) {
    if (isHistoryLesson) {
      return getRHistoryContent(currentTopic, context);
    }

    final quizWidgets = {
      "Module 1 Quiz": (VoidCallback onBack) => RModule1Quiz(onBackToModules: onBack),
      "Module 2 Quiz": (VoidCallback onBack) => RModule2Quiz(onBackToModules: onBack),
      "Module 3 Quiz": (VoidCallback onBack) => RModule3Quiz(onBackToModules: onBack),
      "Module 4 Quiz": (VoidCallback onBack) => RModule4Quiz(onBackToModules: onBack),
      "Module 5 Quiz": (VoidCallback onBack) => RModule5Quiz(onBackToModules: onBack),
      "Module 6 Quiz": (VoidCallback onBack) => RModule6Quiz(onBackToModules: onBack),
      "Module 7 Quiz": (VoidCallback onBack) => RModule7Quiz(onBackToModules: onBack),
      "Module 8 Quiz": (VoidCallback onBack) => RModule8Quiz(onBackToModules: onBack),
    };

    if (quizWidgets.containsKey(currentTopic)) {
      return quizWidgets[currentTopic]!(_backToModules);
    }

    final data = getTopicData(currentTopic);

    return SingleChildScrollView(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          LessonCard(
            title: "Definition",
            content: data["description"] ?? "",
          ),

          LessonCode(
            code: data["code"] ?? "",
            previewCode: data["previewCode"] ?? data["code"] ?? "",
            language: "r",
          ),

          LessonCard(
            title: "Notes",
            content: data["extra"] ?? "",
          ),
        ],
      ),
    );
  }
