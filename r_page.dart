class RPage extends StatefulWidget {
  final String? initialTopic;

  const RPage({
    super.key,
    this.initialTopic,
  });

  @override
  State<RPage> createState() => _RPageState();
}

class _RPageState extends State<RPage> {
  String currentTopic = "R Introduction";
  bool showMenu = false;
  static const String techName = "R";

  bool get isHistoryLesson {
    return rHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...rModules,
      ...rHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "R Lessons";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && rModules.isNotEmpty) {
          currentTopic = rModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && rModules.length > 1) {
          currentTopic = rModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && rModules.length > 2) {
          currentTopic = rModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && rModules.length > 3) {
          currentTopic = rModules[3].lessons.first;
        } else if (currentTopic.contains("Module 5") && rModules.length > 4) {
          currentTopic = rModules[4].lessons.first;
        } else if (currentTopic.contains("Module 6") && rModules.length > 5) {
          currentTopic = rModules[5].lessons.first;
        } else if (currentTopic.contains("Module 7") && rModules.length > 6) {
          currentTopic = rModules[6].lessons.first;
        } else if (currentTopic.contains("Module 8") && rModules.length > 7) {
          currentTopic = rModules[7].lessons.first;
        } else {
          currentTopic = "R Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
      case "Release Date":
        return "August 1993\n\nR was officially released in 1993 as a free software environment for statistical computing and graphics.";
      case "Creator":
        return "Ross Ihaka and Robert Gentleman\n\nR was created by Ross Ihaka and Robert Gentleman while they were professors at the University of Auckland.";
      case "Country of Origin":
        return "New Zealand\n\nR was developed at the University of Auckland in New Zealand.";
      case "Why It Was Created":
        return "R was created to provide researchers, statisticians, and data analysts with a free and powerful programming language for statistical computing, data analysis, and graphical visualization.";
      case "Brief History":
        return "R was inspired by the S programming language developed at Bell Laboratories. Ross Ihaka and Robert Gentleman began developing R in the early 1990s as an open-source alternative. Since its release in 1993, R has become one of the world's leading languages for statistics, machine learning, data science, and academic research.";
      case "Evolution Timeline":
        return "1992\nDevelopment Began\n│\n\n1993\nFirst Public Release\n│\n\n1997\nCRAN Repository Launched\n│\n\n2000\nR 1.0 Released\n│\n\n2010s\nGrowth of Data Science\n│\n\nToday\nR 4.x Series";
      case "Major Milestones":
        return "• 1993 – R was publicly released.\n\n• 1997 – CRAN became the official package repository.\n\n• 2000 – R 1.0 established the language as a mature platform.\n\n• Became one of the most popular tools for statistics and data science.\n\n• Today – Used extensively in research, finance, healthcare, and machine learning.";
      case "Famous Quote":
        return "\"R is free software and a powerful language for statistical computing and graphics.\"\n\n— R Project";
      default:
        return "Learn how R was created and evolved over time.";
    }
  }

