class ArduinoPage extends StatefulWidget {
  final String? initialTopic;

  const ArduinoPage({super.key, this.initialTopic});

  @override
  State<ArduinoPage> createState() => _ArduinoPageState();
}

class _ArduinoPageState extends State<ArduinoPage> {
  String currentTopic = "Arduino Ecosystem";
  bool showMenu = false;

  bool get isHistoryLesson {
    return arduinoHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...arduinoModules,
      ...arduinoHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "Arduino Lessons";
      const String techName = "Arduino";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && arduinoModules.isNotEmpty) {
          currentTopic = arduinoModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && arduinoModules.length > 1) {
          currentTopic = arduinoModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && arduinoModules.length > 2) {
          currentTopic = arduinoModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && arduinoModules.length > 3) {
          currentTopic = arduinoModules[3].lessons.first;
        } else if (currentTopic.contains("Module 5") && arduinoModules.length > 4) {
          currentTopic = arduinoModules[4].lessons.first;
        } else if (currentTopic.contains("Module 6") && arduinoModules.length > 5) {
          currentTopic = arduinoModules[5].lessons.first;
        } else {
          currentTopic = "Arduino Ecosystem";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
      case "Release Date":
        return "2005 - The first official Arduino board was introduced and released in 2005 in Ivrea, Italy.";
      case "Creator":
        return "Massimo Banzi, David Cuartielles, Tom Igoe, Gianluca Martino, and David Mellis. Created to provide an affordable and accessible hardware prototyping platform for students and makers.";
      case "Country of Origin":
        return "Italy - Arduino was originally designed and created at the Interaction Design Institute Ivrea located in Ivrea, Italy.";
      case "Why It Was Created":
        return "Arduino was created to offer an inexpensive, easy-to-use, and open-source prototyping system for students, designers, and hobbyists without deep backgrounds in electronics.";
      case "Brief History":
        return "The project started in 2005 as a tool for students at Interaction Design Institute Ivrea, aiming to replace expensive BASIC Stamp controllers.";
      case "Evolution Timeline":
        return "2005: Project Started in Ivrea, Italy | 2008: Duemilanove Released | 2010: Arduino UNO Released | 2015: IoT Integration | Today: Edge AI & MicroPython";
      case "Major Milestones":
        return "2005: Launch in Italy | 2010: Standard Arduino UNO | 2012: Arduino Due (32-bit ARM) | 2019: Portenta Family | Today: MicroPython & AI Support";
      case "Famous Quote":
        return "\"You don't need anyone's permission to make something great.\" — Massimo Banzi (Arduino Co-Founder)";
      default:
        return "Learn how Arduino was created and evolved over time.";
    }
  }

  @override
