                                          });
                                          Navigator.push(
                                            context,
                                            MaterialPageRoute(
                                              builder: (_) => QuizWidget(
                                                courseTitle: "Arduino",
                                                moduleTitle: "Final Quiz",
                                                questions: arduinoFinalQuizQuestions,
                                                onBackToModules: () {
