class RustPage extends StatefulWidget {
  final String? initialTopic;

  const RustPage({super.key, this.initialTopic});

  @override
  State<RustPage> createState() => _RustPageState();
}

class _RustPageState extends State<RustPage> {
  String currentTopic = "Rust Introduction";
  bool showMenu = false;
  static const String techName = "Rust";

  bool get isHistoryLesson {
    return rustHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...rustModules,
      ...rustHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "Rust Lessons";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && rustModules.isNotEmpty) {
          currentTopic = rustModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && rustModules.length > 1) {
          currentTopic = rustModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && rustModules.length > 2) {
          currentTopic = rustModules[2].lessons.first;
        } else {
          currentTopic = "Rust Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

