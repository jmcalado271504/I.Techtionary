class SqlPage extends StatefulWidget {
  final String? initialTopic;

  const SqlPage({super.key, this.initialTopic});

  @override
  State<SqlPage> createState() => _SqlPageState();
}

class _SqlPageState extends State<SqlPage> {
  String currentTopic = "SQL Introduction";
  bool showMenu = false;

  bool get isHistoryLesson {
    return sqlHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...sqlModules,
      ...sqlHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "SQL Lessons";
      const String techName = "SQL";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && sqlModules.isNotEmpty) {
          currentTopic = sqlModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && sqlModules.length > 1) {
          currentTopic = sqlModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && sqlModules.length > 2) {
          currentTopic = sqlModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && sqlModules.length > 3) {
          currentTopic = sqlModules[3].lessons.first;
        } else if (currentTopic.contains("Module 5") && sqlModules.length > 4) {
          currentTopic = sqlModules[4].lessons.first;
        } else {
          currentTopic = "SQL Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
      case "Release Date":
        return "1974 - SQL was introduced in 1974 by IBM researchers as part of the System R project. It later became the standard language for managing relational databases.";
      case "Creator":
        return "Donald D. Chamberlin & Raymond F. Boyce - Developed SQL at IBM. The language was originally called SEQUEL before being shortened to SQL.";
      case "Country of Origin":
        return "United States - Developed at IBM Research in California, USA, as part of the System R database project.";
      case "Why It Was Created":
        return "SQL was created to make it easier to store, retrieve, update, and manage data in relational databases using simple, human-readable commands.";
      case "Brief History":
        return "Inspired by Edgar F. Codd's relational database model. Standardized by ANSI in 1986 and ISO in 1987. Supported by nearly every major RDBMS including MySQL, PostgreSQL, SQL Server, Oracle, and SQLite.";
      case "Evolution Timeline":
        return "1974: SEQUEL Developed at IBM | 1979: Oracle Released First Commercial SQL Database | 1986: ANSI Standard | 1987: ISO Standard | 1999: Object-Oriented Features | Today: Modern SQL Standards";
      case "Major Milestones":
        return "1974: SQL developed at IBM | 1979: First commercial database by Oracle | 1986: ANSI standard | 1987: ISO standard | 1999: Object-oriented features | Today: Universal relational database language";
      case "Famous Quote":
        return "\"SQL is the universal language of relational databases.\" — Database Community";
      default:
        return "Learn how SQL was created and evolved over time.";
    }
  }

