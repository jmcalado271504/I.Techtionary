  }

  Map<String, dynamic> getTopicData(String topic) {
    try {
      final lesson = sqlLessons.firstWhere(
            (lesson) => lesson.title == topic,
      );

      return {
        "description": lesson.description,
        "code": lesson.code,
        "previewCode": lesson.previewCode ?? lesson.code,
        "extra": lesson.notes,
      };
    } catch (e) {
      return {
        "description": "Lesson not found.",
        "code": "",
        "previewCode": "",
        "extra": "",
      };
    }
  }

  Widget getTopicContent(BuildContext context) {
    if (isHistoryLesson) {
      return getSqlHistoryContent(currentTopic, context);
    }

    final quizWidgets = {
      "Module 1 Quiz": (VoidCallback onBack) => SqlModule1Quiz(onBackToModules: onBack),
      "Module 2 Quiz": (VoidCallback onBack) => SqlModule2Quiz(onBackToModules: onBack),
      "Module 3 Quiz": (VoidCallback onBack) => SqlModule3Quiz(onBackToModules: onBack),
      "Module 4 Quiz": (VoidCallback onBack) => SqlModule4Quiz(onBackToModules: onBack),
      "Module 5 Quiz": (VoidCallback onBack) => SqlModule5Quiz(onBackToModules: onBack),
    };

    if (quizWidgets.containsKey(currentTopic)) {
      return quizWidgets[currentTopic]!(_backToModules);
    }

    final data = getTopicData(currentTopic);

    return SingleChildScrollView(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          LessonCard(
            title: "Definition",
            content: data["description"] ?? "",
          ),

          LessonCode(
            code: data["code"] ?? "",
            previewCode: data["previewCode"] ?? data["code"] ?? "",
            language: "sql",
          ),

          LessonCard(
            title: "Notes",
            content: data["extra"] ?? "",
          ),
        ],
      ),
    );
  }
}