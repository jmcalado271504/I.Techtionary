class PandasPage extends StatefulWidget {
  final String? initialTopic;

  const PandasPage({
    super.key,
    this.initialTopic,
  });

  @override
  State<PandasPage> createState() => _PandasPageState();
}

class _PandasPageState extends State<PandasPage> {
  String currentTopic = "Pandas Introduction";
  bool showMenu = false;
  static const String techName = "Pandas";

  bool get isHistoryLesson {
    return pandasHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...pandasModules,
      ...pandasHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "Pandas Lessons";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && pandasModules.isNotEmpty) {
          currentTopic = pandasModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && pandasModules.length > 1) {
          currentTopic = pandasModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && pandasModules.length > 2) {
          currentTopic = pandasModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && pandasModules.length > 3) {
          currentTopic = pandasModules[3].lessons.first;
        } else {
          currentTopic = "Pandas Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

