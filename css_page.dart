class CssPage extends StatefulWidget {
  final String? initialTopic;

  const CssPage({super.key, this.initialTopic});

  @override
  State<CssPage> createState() => _CssPageState();
}

class _CssPageState extends State<CssPage> {
  String currentTopic = "CSS Introduction";
  bool showMenu = false;

  bool get isHistoryLesson {
    return cssHistoryModules.any(
          (module) => module.lessons.contains(currentTopic),
    );
  }

  Module? get currentModule {
    final allModules = [
      ...cssModules,
      ...cssHistoryModules,
    ];

    for (final module in allModules) {
      if (module.lessons.contains(currentTopic)) {
        return module;
      }
    }

    return null;
  }

  @override
  void initState() {
    super.initState();

    if (widget.initialTopic != null) {
      currentTopic = widget.initialTopic!;
    }

    _saveLessonHistory(currentTopic);
  }

  void _saveLessonHistory(String topic) async {
    if (topic.contains("Quiz")) return;

    final user = FirebaseAuth.instance.currentUser;
    if (user != null) {
      final module = currentModule;
      final moduleTitle = module?.title ?? "CSS Lessons";
      const String techName = "CSS";

      final String cleanTopic = topic.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final docId = "${user.uid}_${techName}_$cleanTopic";

      await FirebaseFirestore.instance
          .collection('lesson_history')
          .doc(docId)
          .set({
        'userId': user.uid,
        'techName': techName,
        'moduleTitle': moduleTitle,
        'lessonTitle': topic,
        'visitedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    }
  }

  void _backToModules() {
    setState(() {
      final module = currentModule;

      if (module != null && module.lessons.isNotEmpty) {
        currentTopic = module.lessons.first;
      } else {
        if (currentTopic.contains("Module 1") && cssModules.isNotEmpty) {
          currentTopic = cssModules[0].lessons.first;
        } else if (currentTopic.contains("Module 2") && cssModules.length > 1) {
          currentTopic = cssModules[1].lessons.first;
        } else if (currentTopic.contains("Module 3") && cssModules.length > 2) {
          currentTopic = cssModules[2].lessons.first;
        } else if (currentTopic.contains("Module 4") && cssModules.length > 3) {
          currentTopic = cssModules[3].lessons.first;
        } else if (currentTopic.contains("Module 5") && cssModules.length > 4) {
          currentTopic = cssModules[4].lessons.first;
        } else if (currentTopic.contains("Module 6") && cssModules.length > 5) {
          currentTopic = cssModules[5].lessons.first;
        } else {
          currentTopic = "CSS Introduction";
        }
      }
    });
    _saveLessonHistory(currentTopic);
  }

  String _getHistoryTopicText(String topic) {
    switch (topic) {
      case "Release Date":
        return "December 17, 1996 - CSS Level 1 became an official W3C Recommendation on December 17, 1996.";
      case "Creator":
        return "Håkon Wium Lie - Proposed the idea of Cascading Style Sheets (CSS) in 1994 while working at CERN. Together with Bert Bos, he developed CSS into the style sheet language widely used on the web today.";
      case "Country of Origin":
        return "Switzerland - CSS was first proposed at CERN, the European Organization for Nuclear Research, located in Geneva, Switzerland.";
      case "Why It Was Created":
        return "CSS was created to separate the design of a webpage from its content. Before CSS, HTML was responsible for both structure and presentation, making web pages difficult to maintain.";
      case "Brief History":
        return "CSS was proposed in 1994 by Håkon Wium Lie. In 1996, CSS Level 1 became an official W3C Recommendation. Over the years, CSS evolved with new versions introducing layouts, animations, responsive design, Flexbox, Grid, and modern features.";
      case "Evolution Timeline":
        return "1994: CSS Proposed | 1996: CSS Level 1 | 1998: CSS Level 2 | 2011: CSS3 Modules | Today: Modern CSS (Flexbox, Grid, Variables, Animations)";
      case "Major Milestones":
        return "1994: Proposed by Håkon Wium Lie | 1996: CSS Level 1 W3C Recommendation | 1998: CSS Level 2 introduced positioning | 2011: CSS3 modular approach | Today: Grid, Flexbox, Variables, Container Queries";
      case "Famous Quote":
        return "\"HTML is for structure. CSS is for presentation.\" — Web Design Principle";
      default:
        return "Learn how CSS was created and evolved over time.";
    }
  }

